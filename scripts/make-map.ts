/**
 * Builds src/data/japanMap.ts: simplified SVG paths of Japan's prefectures,
 * projected for the travel map. Run once; the output is committed.
 *   curl -L https://raw.githubusercontent.com/dataofjapan/land/master/japan.geojson -o /tmp/japan.geojson
 *   npx tsx scripts/make-map.ts /tmp/japan.geojson
 * Source: dataofjapan/land (prefecture boundaries, MIT).
 */
import { readFileSync, writeFileSync } from "node:fs";
import { BBOX, project } from "../src/lib/geo";

type Ring = [number, number][];
const src = JSON.parse(readFileSync(process.argv[2], "utf8"));

/** Douglas–Peucker in degrees. */
function simplify(pts: Ring, tol: number): Ring {
  if (pts.length < 4) return pts;
  const keep = new Uint8Array(pts.length);
  keep[0] = keep[pts.length - 1] = 1;
  const stack: [number, number][] = [[0, pts.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop()!;
    const [ax, ay] = pts[a], [bx, by] = pts[b];
    const dx = bx - ax, dy = by - ay, len = Math.hypot(dx, dy) || 1e-12;
    let maxD = 0, idx = -1;
    for (let i = a + 1; i < b; i++) {
      const d = Math.abs(dy * pts[i][0] - dx * pts[i][1] + bx * ay - by * ax) / len;
      if (d > maxD) { maxD = d; idx = i; }
    }
    if (maxD > tol && idx > 0) { keep[idx] = 1; stack.push([a, idx], [idx, b]); }
  }
  return pts.filter((_, i) => keep[i]);
}

const area = (r: Ring) => Math.abs(r.reduce((s, [x, y], i) => { const [x2, y2] = r[(i + 1) % r.length]; return s + x * y2 - x2 * y; }, 0) / 2);
const inBox = ([x, y]: [number, number]) => x > BBOX.west - 1 && x < BBOX.east + 1 && y > BBOX.south - 1 && y < BBOX.north + 1;

const prefectures: { name: string; d: string }[] = [];
for (const f of src.features) {
  const polys: Ring[][] = f.geometry.type === "Polygon" ? [f.geometry.coordinates] : f.geometry.coordinates;
  let d = "";
  for (const poly of polys) {
    const outer = poly[0];
    if (area(outer) < 0.004 || !outer.some(inBox)) continue; // drop specks & far islands
    // Closed ring: split at the point farthest from the start so each half has a baseline.
    let far = 0, best = 0;
    outer.forEach(([x, y], i) => { const dd = Math.hypot(x - outer[0][0], y - outer[0][1]); if (dd > best) { best = dd; far = i; } });
    const s = [...simplify(outer.slice(0, far + 1), 0.012), ...simplify(outer.slice(far), 0.012).slice(1)];
    if (s.length < 4) continue;
    d += "M" + s.map((p) => project(p[0], p[1]).map((n) => n.toFixed(1)).join(",")).join("L") + "Z";
  }
  if (d) prefectures.push({ name: f.properties.nam_ja, d });
}

const out = `// Generated by scripts/make-map.ts from dataofjapan/land (MIT). Do not edit.\nexport const PREFECTURES: { name: string; d: string }[] = ${JSON.stringify(prefectures)};\n`;
writeFileSync("src/data/japanMap.ts", out);
console.log(`${prefectures.length} prefectures, ${(out.length / 1024).toFixed(0)} KB`);
